export function getBrandForName(name) {
  if (!name) return BRANDS.ipark
  const lower = name.toLowerCase()
  const hit = BRAND_MATCH.find((b) => lower.includes(b.match.toLowerCase()))
  return hit ? BRANDS[hit.brand] : BRANDS.ipark
}
